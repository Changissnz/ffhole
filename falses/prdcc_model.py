"""
function outputs list, of variable size, all elements belong to constituents `c`.
"""
def generate_form_P_function(prg): 
    cycle_length = modulo_in_range(int(prg()),DEFAULT_PRDCC_PRNG_CYCLE_LENGTH_RANGE) 
    G = generate_PRNG_struct__type_NAIC_V2(prg,cycle_length)

    G.reset(reset_index=True,v=int(prg())) 

    def f(idn,c): 
        c = sorted(c) 

        G.reset(reset_index=True) 
        prg1 = G.__next__ 

        s0 = ceil(DEFAULT_PRDCC_FUNCTION_GEN_PERM_LENGTH_RATIO_RANGE[0] * len(c)) 
        s1 = ceil(DEFAULT_PRDCC_FUNCTION_GEN_PERM_LENGTH_RATIO_RANGE[1] * len(c))
        assert s0 >= len(c) 

        # start off w/ all elements from `c` (all constituents have to be used)
        c2 = prg_seqsort(deepcopy(c),prg1) 
        num_elements = modulo_in_range(int(prg1()),[s0,s1+1]) 
        num_elements = num_elements - len(c) 

        if num_elements == 0: 
            return c2 

        # choose the remaining elements 
        prg1 = prg__single_to_int(prg1)
        c_ = prg_choose_n(c,num_elements,prg1,is_unique_picker=False) 
        c2.extend(c_)
        return c2 
    
    return f 

"""
function outputs sequence, w/ every element either a 
[0] constituent in `c` (repetitions allowed),
[1] edge between two constituents of `c`. 
"""
def generate_form_G_function(prg): 

    cycle_length = modulo_in_range(int(prg()),DEFAULT_PRDCC_PRNG_CYCLE_LENGTH_RANGE) 
    G = generate_PRNG_struct__type_NAIC_V2(prg,cycle_length)
    G.reset(reset_index=True,v=int(prg())) 

    def f(idn,c): 
        c = sorted(c) 
        G.reset(reset_index=True) 

        prg_ = G.__next__
        node_list = generate_form_P_function(prg_)(idn,c) 
        edge_conn_range = DEFAULT_PRDCC_FUNCTION_GEN_GRAPH_EDGE_CONNECTIVITY_RANGE(len(node_list)) 
        edge_conn = float(round(prg_decimal(prg_,edge_conn_range),5))

        gg = GraphGen(is_dsg=False,prg=prg_,is_realtime_gen=bool(int(prg_()) % 2),\
            vertex_degree=len(node_list),edge_connectivity=edge_conn) 
        gg.full_run() 
        
        graph_nodes = sorted(gg.d.keys())
        gnode2c_map = dict() 
        for (i,n) in enumerate(graph_nodes): 
            gnode2c_map[n] = node_list[i] 

        g = gg.d 
        edge_list = [] 

        for k,v in g.items(): 
            one = gnode2c_map[k]
            for v_ in v: 
                two = gnode2c_map[v_] 
                edge_list.append((one,two))
        
        q = node_list 
        q.extend(edge_list)
        return q 
    return f 

"""
function outputted from this function takes the following 
parameters:
- identity of element 
- constituents 
"""
def generate_form__identity(): 

    def f(idn,c): 
        return [idn] 

    return f 

"""
(P)seudo-(R)andom (D)erivable (C)onstituent (C)omposition Function Generator.

Used for generating:
- formulation functions that map out constituents of an element to their respective 
  structure. Structures able to be generated by this generator are: 
  (I) permutation w/ repetition of constituents 
  (II) graphs of constituents, after permutation w/ repetition of constituents; 
       every constituent has a node subset of graph that can be of size greater than 1. 

The output from both types of formulation functions can be used as input for 
function<instability_score_vector>. 

NOTE: this generator design is specialized for class<KernelReprTypeDCCWSM>. 
""" 
class PRDCCFunctionGen: 

    def __init__(self,starting_label_set,prg,form_type): 
        assert type(starting_label_set) in {set,list} 
        assert len(starting_label_set) == len(set(starting_label_set)) 
        assert type(prg) in {MethodType,FunctionType} 
        assert form_type in DEFAULT_PRDCC_FUNCTION_GEN_FORM_TYPES

        self.label_seq = sorted(starting_label_set) 
        self.label_seq = [str(l) for l in self.label_seq]
        self.prg = prg 
        self.ftype = form_type

        # label-to-integer map, <Label2IntMap>.
        self.l2i_map = None 
        # label -> (formulation function, instability function) 
        self.l2f_map = dict() 
        self.preproc() 
        return 

    def preproc(self): 
        s_func = DEFAULT_L2INT_STRINGIZE_FUNC
        s_inv = DEFAULT_L2INT_DESTRINGIZE_FUNC(str,True)

        self.l2i_map = Label2IntMap(self.label_seq,\
            s_func,s_inv,enable_bimap=True)

        for l in self.label_seq: 
            f_func,s_func = generate_form__identity(),instability_score_vector
            i = self.l2i_map.element_to_int_label(l) 
            self.l2f_map[i] = (f_func,s_func) 
        return 

    """
    main method #1 
    """
    def add_element(self,constituents:set):  
        # verify that all members of constituent set 
        # already exist in map 
        for c in constituents: 
            assert self.element_to_int_label(c) != -1 

        self.l2i_map.add_element(constituents) 
        de_int = self.element_to_int_label(constituents)
        self.l2f_map[de_int] = self.generate_functions_for_element() 

    """
    main method #2
    """ 
    def generate_functions_for_element(self): 

        f_func = self.generate_f_function()
        return f_func,instability_score_vector

    def element_to_int_label(self,element): 
        return self.l2i_map.element_to_int_label(element) 

    def int_label_to_element(self,i):
        return self.l2i_map.int_label_to_element(i) 

    def generate_f_function(self): 
        if self.ftype == "P": 
            return generate_form_P_function(self.prg)  
        return generate_form_G_function(self.prg) 