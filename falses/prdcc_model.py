# P -> permutation w/ repetition 
# G -> undirected simple graph 
DEFAULT_PRDCC_FUNCTION_GEN_FORM_TYPES = {"P","G"}

DEFAULT_PRDCC_FUNCTION_GEN_PERM_LENGTH_RATIO_RANGE = [1.0,5.0]
DEFAULT_PRDCC_FUNCTION_GEN_GRAPH_NODESIZE_RATIO_RANGE = DEFAULT_PRDCC_FUNCTION_GEN_PERM_LENGTH_RATIO_RANGE

DEFAULT_PRDCC_PRNG_CYCLE_LENGTH_RANGE = [15,42] 

"""
outputs a ratio range for edge connectivity of graphs generated by 
the form G (graph). 

Ratio range limits the number of possible edges. 
"""
def DEFAULT_PRDCC_FUNCTION_GEN_GRAPH_EDGE_CONNECTIVITY_RANGE(num_nodes): 
    num_edges = max_simple_edges(num_nodes) 
    r = None 

    # case: excessive number of possible edges, place limit of 2000 
    if num_edges >= 2000: 
        r = [200 / num_edges,2000 / num_edges]
    else: 
        r = [0.2,0.42] 
    return r 

