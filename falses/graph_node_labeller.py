from xFS_bots.graph_models.bfs import * 
from xFS_bots.graph_models.dfs import * 
from morebs2.numerical_generator import prg_decimal,prg_seqsort_ties,prg_to_prg__LCG_sequence,modulo_in_range
from morebs2.matrix_methods import is_valid_range
from types import FunctionType,MethodType
from collections import Counter 

def constant_decimal_multiple_function(d): 
    assert 0. <= d <= 1.

    def f(m): 
        assert 0. <= m <= 1. 
        return m * d 

    return f 

def prg_decreasing_decimal_delta_function(prg,delta_range=[0.,0.5]):

    assert type(prg) in {MethodType,FunctionType} 
    assert is_valid_range(delta_range,False,False)
    assert 0. <= delta_range[0] < delta_range[1] <= 1.

    def f(m): 
        q = prg_decimal(prg,delta_range)
        return m - q 

    return f 

"""
Node Labelling Function Type (S)ub-(G)raph (A)ctivation. 

Main method<__next__> labels nodes of a simple, undirected graph by 
breadth-first or depth-first search order. 

        **Rules for labelling a node n, with parent n_p** 
- If parent n_p does not exist (n is start node), use PRNG to assign it a label l from 
  `label_set`, a weight w in [0.5,1.], and a label activation function f_l. 
- Otherwise,
    - Let f_p be the label activation function of parent node n_p. 
    - Apply f_p to produce the weight w_n for for n: 
        f_p(`node2weight_map`[n_p][1]) = w_n. 
    - Update the transmission weight of n_p to w_n: 
        `node2weight_map`[n_p][1] = w_n. 
    - If w_n >= 0.5:
        - label of node n is that of node n_p. 
        - weight of node n is w_n. 
        - label activation function of node n is f_p (parent function is transmitted to it). 
    - Otherwise, 
        - label l' of node n is chosen by PRNG to be the most counter (in terms of neighbor label frequency). 
        - weight w' of node n is chosen by PRNG to satisfy 
                w' in [0.5,1.0]. 
        - label activation function of node n generated by PRNG. 

------------------------------------------------------------------------
G := defaultdict, subject graph 
start_node := None XOR node in G 
is_bfs := bool, ?is breadth-first search? 
label_set := set, available labels to label node 
activation_function_type := str, 'multiple'|'prng delta'|'both' 
prg := PRNG 
verbose := bool 
"""
class NodeLabellingFunctionTypeSGA:

    def __init__(self,G,start_node,is_bfs:bool,label_set,activation_function_type,prg,\
        verbose:bool=False): 
        assert type(G) in {defaultdict,dict} 
        assert type(start_node) == type(None) or start_node in G 
        assert type(is_bfs) == bool 
        assert type(label_set) == set 
        assert activation_function_type in {"multiple","prng delta","both"}  
        assert type(prg) in {MethodType,FunctionType}
        assert type(verbose) == bool 

        self.G = G 
        self.start_node = start_node
        self.is_bfs = is_bfs 
        self.label_set = label_set 
        self.afunc_type = activation_function_type
        self.prg = prg 
        self.verbose = verbose 

        # maps related to labelling of nodes 
        #   node idn -> label
        self.node2label_map = dict() 
        #   node idn -> F (activation function for +/- label)
        self.node2actfunc_map = dict() 
        #   node idn -> [initial weight, transmission weight]
        self.node2weight_map = dict() 
        
        self.fin_stat = False 
        self.gtrav = None 

        self.preproc() 
        return 

    def preproc(self): 
        if type(self.start_node) == type(None): 
            nodes = sorted(self.G.keys())
            i = int(self.prg()) % len(nodes) 
            self.start_node = nodes[i]

        if self.is_bfs: 
            nextnode_priority_function = DEFAULT_PRNG_TO_NEXTNODE_PRIORITY_FUNCTION__BFS(self.prg)
            self.gtrav = BFSCache(self.start_node,self.G,\
                edge_cost_function=DEFAULT_EDGE_COST_FUNCTION,\
                nextnode_priority_function=nextnode_priority_function,no_duplicate_touch_nodes=True)
        else: 
            nextnode_priority_function = DEFAULT_PRNG_TO_NEXTNODE_PRIORITY_FUNCTION__DFS(self.prg)
            self.gtrav = DFSCache(self.start_node,self.G,\
                edge_cost_function=DEFAULT_EDGE_COST_FUNCTION,search_head_type=1,\
                nextnode_priority_function=nextnode_priority_function,no_duplicate_touch_nodes=True)

        self.label_node(self.start_node,None) 
        return

    def __next__(self): 
        if self.fin_stat: return 

        stat = False 
        q = None 
        while not stat and not self.fin_stat: 
            q = self.travel_to_next_nodes() 
            if type(q) != type(None): 
                stat = True 

            if self.verbose: 
                if type(q) != type(None): 
                    print("labelled nodes: ",q) 
        return q 

    def travel_to_next_nodes(self): 
        if self.fin_stat: 
            return 

        if self.gtrav.fin_stat:
            self.fin_stat = True 
            return 
        
        touched = deepcopy(self.gtrav.touched_nodes) 
        ref = self.gtrav.reference 
        self.gtrav.move_one() 

        prev_edges = self.gtrav.previous_edges
        new_nodes = set([p[1] for p in prev_edges]) - touched 
        if len(new_nodes) == 0: 
            return self.travel_to_next_nodes() 

        new_nodes = prg_seqsort(sorted(new_nodes),self.prg) 
        for node in new_nodes: self.label_node(node,ref)
        return new_nodes 
        
    def label_node(self,node,parent_node): 
        # case: start 
        if type(parent_node) == type(None): 
            q = sorted(self.label_set) 
            i = int(self.prg()) % len(q) 
            label = q[i] 

            weight = prg_decimal(self.prg,[0.5,1.]) 
            F = self.generate_afunc() 

            self.node2actfunc_map[node] = F 
            self.node2label_map[node] = label 
            self.node2weight_map[node] = [weight,weight]  
            return 

        # case: node has parent. Node is labeled as that of 
        #       parent or counter to it. 
        F = self.node2actfunc_map[parent_node] 
        w = self.node2weight_map[parent_node][1] 
        
        q = F(w) 
        
        self.node2weight_map[parent_node][1] = q 

        # case: node is labelled as parent 
        if q >= 0.5: 
            l = self.node2label_map[parent_node] 
            f = F 
            w2 = q 
            if self.verbose: 
                print("new node {} same {} weight {}".format(node,l,w2)) 
        # case: choose a different label 
        else: 
            l = self.counter_label_for_node(node)
            f = self.generate_afunc() 
            w2 = prg_decimal(self.prg,[0.5,1.]) 

            if self.verbose: 
                print("new node {} label {} parent/label {}/{} weight {}".format(node,l,parent_node,\
                    self.node2label_map[parent_node],w2)) 

        self.node2label_map[node] = l 
        self.node2actfunc_map[node] = f 
        self.node2weight_map[node] = [w2,w2] 
        return 

    def counter_label_for_node(self,node): 
        c = Counter([self.node2label_map[n] for n in self.G[node] if n \
            in self.node2label_map]) 
        for l in self.label_set: 
            if l not in c: c[l] = 0 
        c2 = [(k,v) for k,v in c.items()]

        q = prg_seqsort_ties(c2,self.prg,vf=lambda x:x[1]) 
        return q[0][0] 

    #------------------------------------- generates functions assigned to nodes 

    def generate_afunc(self): 
        if self.afunc_type == "multiple": 
            return self.generate_afunc__CDM()
        elif self.afunc_type == "prng delta": 
            return self.generate_afunc__PRNG() 
        else: 
            return self.generate_afunc__CDM() if \
                int(self.prg()) % 2 else self.generate_afunc__PRNG()

    def generate_afunc__CDM(self):
        d = prg_decimal(self.prg,[0.5,1.0]) 
        return constant_decimal_multiple_function(d) 

    def generate_afunc__PRNG(self): 
        mod_scale = modulo_in_range(self.prg(),[1+1/16,4-5/9])
        prg = prg_to_prg__LCG_sequence(self.prg,1,moduli_scale=mod_scale)[0]
        return prg_decreasing_decimal_delta_function(\
            prg,delta_range=[0.,0.25])