"""
(A)uto-(G)enerating Chained Label Interpreter Type (C)lass-(E)xpected (E)ffect. 

Starts with an initial <LabelInterpreterTypeCEE> and complementary <KernelReprTypeDCCWSM>. 

Both of these operate on integer labels, despite the initial form of the constituents in 
`c2w_map`; all base constituents are assigned integers, and every additional element of 
sets of base constituents or other elements are also assigned integers. This assignment, 
as well as the formulation functions, are generated by an instance of <PRDCCFunctionGen>. 

When method<update_with_s_path> is called, w/ `add_to_chain` set to True, if the S-path 
(skew path) is not a direct path, for any index with a multi-label, the multi-label 
is a new element. These new elements, along w/ the ones at the previous link in the 
chain, `I`, comprise the new label set, in the case of `maintain_constant_dim` set to 
False. When `maintain_constant_dim` is set to True, the new label set is of the same 
size as that of `I`.This new label set is used to instantiate the next <LabelInterpreterTypeCEE>. 

            NOTE: 
The `form_type` specifies the constituent form, generated from the constituents, of every 
non-base elements. 
- `P`: permutation w/ repetition, 
- `G`: graph of permutation w/ repetition. 
"""  
class AGChainedLabelInterpreterTypeCEE: 

    def __init__(self,c2w_map:dict,prg,form_type,maintain_constant_dim:bool=False): 
        assert type(prg) in {MethodType,FunctionType}
        assert type(maintain_constant_dim) == bool 

        self.prg = prg 
        self.pfgen = None 
        self.I = None 
        self.K = None 
        self.maintain_constant_dim = maintain_constant_dim

        self.i_chain = deque() 
        self.preproc(c2w_map,form_type) 
        return

    def __getitem__(self,i):
        if isinstance(i, slice): 
            return self.i_chain.__getitem__(i)    

        if type(i) in {list,np.ndarray}:
            qx = []
            for i_ in i:
                qx.append(self.__getitem__(i_))
            return qx 

        assert i < len(self) 
        return self.i_chain[i] 

    def __len__(self): 
        return len(self.i_chain)  

    def preproc(self,c2w_map:dict,form_type): 
        label_seq = sorted(c2w_map.keys()) 
        self.pfgen = PRDCCFunctionGen(label_seq,self.prg,form_type)

        int_label_seq = [self.pfgen.base_to_int_idn(b) for b in label_seq] 
        self.I = LabelInterpreterTypeCEE(deepcopy(int_label_seq)) 

        c2w_map_ = {self.pfgen.base_to_int_idn(k): v for k,v in c2w_map.items()}
        self.K = KernelReprTypeDCCWSM(int_label_seq,c2w_map_,idn_func=generate_form__identity)
        return 

    #----------------------------------- update methods used to add more links to chain 

    def update_with_s_path(self,element,skew,skew_direction=1,add_to_chain:bool=True): 
        assert type(add_to_chain) == bool 

        P = self.I.label_to_s_path(element,skew,skew_direction)
        M = self.I.path_to_lmap(P)

        # iterate through every index and check for existence 
        l = len(self.I) 
        for i in range(l): 
            E = M[i]
            self.update_kernel(E) 

        if add_to_chain:
            self.add_link(M) 
        return 

    def add_link(self,M): 
        indices = sorted(M.keys())
        q = [M[i] for i in indices] 

        labels = [self.pfgen.element_to_int_label(q_) for q_ in q]

        if not self.maintain_constant_dim: 
            L = deepcopy(self.I.label_seq)
            labels = [l for l in labels if l not in L] 
            labels = L + labels 
            
        self.i_chain.append(self.I) 
        self.I = LabelInterpreterTypeCEE(labels) 
        return 

    def update_kernel(self,element): 

        # case: element already found 
        if element in self.pfgen or len(element) < 2: 
            return 

        self.pfgen.add_element(element) 
        i = self.pfgen.element_to_int_label(element) 

        f0,f1 = self.pfgen.i2f_map[i]
        self.add_edge_weights(i,element,f0)

        w = float(round(prg_decimal(self.prg,[0.,1.]),5))
        self.K.add_element(i,element,f0,f1,w)
        return 

    def add_edge_weights(self,idn,element,f0): 
        # case: edge weights pertain only to G-form. 
        if self.pfgen.ftype == "P": return 

        qx = f0(idn,element)

        new_weights = dict() 
        for q in qx: 
            if type(q) != tuple: 
                continue 

            if q in self.K.weight_map:
                continue 

            new_weights[q] = float(round(prg_decimal(\
                self.prg,[0.,1.]),5))

        self.K.add_weights(new_weights,overwrite_elements=False) 

    
    #-------------------------------------------------- methods to calculate instability 
    #-------------------------------------------------- 

    """
    the instability vector of an S-path is the ordered concatenation of every index's 
    instability vector for the <LabelInterpreterTypeCEE> @ index `intrp_index`.
    """
    def s_path_instability_vec(self,intrp_index,label,skew,skew_direction=1,verbose:bool=False): 
        assert type(verbose) == bool 

        I = self.fetch_intrp(intrp_index) 
        P = I.label_to_s_path(label,skew,skew_direction)
        M = I.path_to_lmap(P)

        l = len(I)
        V = [] 
        for i in range(l): 
            s = M[i] 
            if verbose: print("*\t{} --> {}".format(i,s)) 
            j = self.pfgen.element_to_int_label(s)
            V.extend(self.element_instability_vec(j))  

        return V 

    def fetch_intrp(self,index): 
        assert 0 <= index <= len(self.i_chain) + 1 
        if index == len(self.i_chain) + 1: 
            return self.I 
        return self.i_chain[index]

    """
    element := int, integer label for element 
    """
    def element_instability_vec(self,element): 
        return self.K.instability_vec(element)

    """
    return: 
    - the integer label pertaining to the `constituents`. 
    """
    def constituents_to_label(self,constituents): 
        return self.pfgen.element_to_int_label(constituents) 